import {chromium} from 'playwright';
import {preview} from 'vite';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';

const out=fileURLToPath(new URL('../test-results/',import.meta.url));
fs.mkdirSync(path.join(out,'screenshots'),{recursive:true});
fs.mkdirSync(path.join(out,'validation'),{recursive:true});
const server=await preview({preview:{host:'127.0.0.1',port:0,strictPort:true}});
const url=`http://127.0.0.1:${server.httpServer.address().port}/`;
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1672,height:941},deviceScaleFactor:1});
const errors=[],requests=[],checks=[];
page.on('pageerror',e=>errors.push(String(e)));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
page.on('requestfailed',r=>errors.push(`${r.url()}: ${r.failure()?.errorText}`));
page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`);});
page.on('request',r=>requests.push(r.url()));
let failure;
try {
  const response=await page.goto(url);
  assert.equal(response.status(),200);
  await page.locator('.scene-loading').waitFor({state:'detached'});
  assert.equal(await page.evaluate(()=>typeof window.__b1),'undefined');
  assert.equal(await page.locator('.debug-toggle, canvas').count(),0);
  assert.equal(await page.locator('a[href*="m1.html"]').count(),0);
  assert.equal(await page.locator('.character').count(),4);
  assert.equal(await page.locator('[data-pose="seated"]').count(),3);
  assert.equal(await page.locator('[data-character="receptionist"]').count(),1);
  await page.screenshot({path:path.join(out,'screenshots/production-first-screen.png'),animations:'disabled'});
  checks.push('Default root opens the built Demo; 3 seated leads + reception; no legacy entry, debug hooks or 3D canvas');
  await page.getByRole('button',{name:'空间导览 ↗',exact:true}).click();
  assert.equal(await page.locator('.people-grid button').count(),7);
  await page.getByRole('button',{name:'关闭窗口'}).click();
  await page.locator('[data-character="receptionist"]').click();
  await page.getByRole('heading',{name:'接待员',exact:true}).waitFor();
  await page.keyboard.press('Escape');
  await page.locator('[data-character="design-lead"]').click();
  await page.getByRole('dialog').waitFor();
  await page.screenshot({path:path.join(out,'screenshots/production-agent-dialog.png'),animations:'disabled'});
  await page.getByRole('button',{name:'关闭窗口'}).click();
  checks.push('Production guide and distinct reception / lead dialogs open and close');
  await page.locator('.scene-transport').getByLabel('播放速度').selectOption('4');
  await page.getByRole('button',{name:'播放演示',exact:true}).click();
  await page.getByTestId('decision-notice').waitFor();
  assert.equal(await page.locator('[data-pose="seated"]').count(),0);
  assert.equal(await page.locator('[data-character$="worker"]').count(),2);
  await page.getByTestId('decision-notice').click();
  await page.getByRole('button',{name:'批准方向并继续'}).click();
  await page.getByRole('button',{name:'关闭窗口'}).click();
  await page.locator('.scene-transport .transport-play').filter({hasText:'已完成'}).waitFor();
  assert.equal(await page.locator('[data-pose="seated"]').count(),3);
  assert.equal(await page.locator('.character').count(),4);
  await page.locator('[data-region-label="showcase"]').click();
  await page.getByRole('tab',{name:'交付报告'}).click();
  assert.equal(await page.getByRole('tabpanel').getByText('模拟通过',{exact:true}).count(),3);
  await page.screenshot({path:path.join(out,'screenshots/production-artifact-report.png'),animations:'disabled'});
  checks.push('Real UI approval reaches delivery, releases workers, seats leads and exposes 3 explicitly Mock checks');
  assert.deepEqual(errors,[]);
  assert.ok(requests.every(u=>u.startsWith(url)||u.startsWith('data:')||u.startsWith('blob:')));
  assert.equal(new Set(requests.filter(u=>u.endsWith('.png'))).size,11);
  assert.ok(!requests.some(u=>/\.(glb|gltf)(?:\?|$)|three\.module/.test(u)));
  checks.push('All 11 PNGs load; no external requests, models, console errors or failed resources');
} catch(error) {
  failure=String(error.stack??error);
  await page.screenshot({path:path.join(out,'screenshots/production-failure.png')}).catch(()=>{});
  process.exitCode=1;
} finally {
  fs.writeFileSync(path.join(out,'validation/production.json'),JSON.stringify({passed:!failure,url,checks,errors,failure,requests:[...new Set(requests)]},null,2));
  await browser.close();
  await new Promise(resolve=>server.httpServer.close(resolve));
}
console.log(JSON.stringify({passed:!failure,checks,errors,failure},null,2));
